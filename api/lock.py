"""Regenerate api/requirements.lock: every package the Docker image installs,
at an exact version, with the hashes pip checks (--require-hashes).

    pip install uv && python api/lock.py

Run it after changing a dependency in api/pyproject.toml, and commit the
result. Dependabot also proposes updates to the lock file.
"""

from __future__ import annotations

import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXTRAS = ("photo", "ai", "queue")  # what api/Dockerfile installs
LOCAL = {"pcdoctor-analysis"}  # this repository's own package, installed separately


def main() -> int:
    project = tomllib.loads((HERE / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    wanted = [d for d in project["dependencies"] if d.split("[")[0].split(">")[0] not in LOCAL]
    for extra in EXTRAS:
        wanted += project["optional-dependencies"][extra]
    source = HERE / "requirements.in"
    source.write_text(
        "# Generated by api/lock.py from api/pyproject.toml - do not edit by hand.\n"
        + "\n".join(sorted(set(wanted)))
        + "\n",
        encoding="utf-8",
    )
    return subprocess.call(
        [
            "uv",
            "pip",
            "compile",
            "requirements.in",
            "--custom-compile-command",
            "python api/lock.py",
            "--universal",  # one lock for every platform (amd64 and arm64 images)
            "--python-version",
            "3.13",  # api/Dockerfile's Python
            "--generate-hashes",
            "--quiet",
            "--output-file",
            "requirements.lock",
        ],
        cwd=HERE,
    )


if __name__ == "__main__":
    sys.exit(main())
